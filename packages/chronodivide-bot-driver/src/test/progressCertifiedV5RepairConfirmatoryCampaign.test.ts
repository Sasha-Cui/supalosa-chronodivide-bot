import { describe, expect, it } from "vitest";
import {
    PROGRESS_CERTIFIED_V5_DEPLOYABILITY_ARRAY_JOB_ID,
    PROGRESS_CERTIFIED_V5_DEPLOYABILITY_FINALIZER_JOB_ID,
    PROGRESS_CERTIFIED_V5_DEPLOYABILITY_SUMMARY_SHA256,
    PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_COUNTRIES,
    PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_ENGINE_SEED_BASE,
    PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_FAMILY_COUNT,
    PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_LAUNCH_COUNT,
    PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_MAX_TICKS,
    PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_ONE_SIDED_95_T_CRITICAL_DF52,
    PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_PROTOCOL_SHA256,
    PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_SHARD_COUNT,
    PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_SUCCESS_RULE,
    PROGRESS_CERTIFIED_V5_REPAIR_RESULT_SHA256,
} from "../training/progressCertifiedV5RepairConfirmatoryCampaign.js";

describe("progress-certified V5 repaired confirmatory campaign freeze", () => {
    it("uses the complete 53-family repaired population across countries and slots", () => {
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_FAMILY_COUNT).toBe(53);
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_COUNTRIES).toHaveLength(9);
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_SHARD_COUNT).toBe(477);
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_LAUNCH_COUNT).toBe(2_862);
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_ENGINE_SEED_BASE).toBe(4_232_000_000);
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_MAX_TICKS).toBe(24_000);
    });

    it("freezes the repaired technical evidence and co-primary success rule", () => {
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_SUCCESS_RULE).toHaveLength(3);
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_SUCCESS_RULE[0]).toContain("2862");
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_SUCCESS_RULE[1]).toContain("V5-minus-external");
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_SUCCESS_RULE[2]).toContain("minus 0.5");
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_ONE_SIDED_95_T_CRITICAL_DF52)
            .toBeCloseTo(1.6746891537260253, 15);
        expect(PROGRESS_CERTIFIED_V5_REPAIR_CONFIRMATORY_PROTOCOL_SHA256).toMatch(/^[0-9a-f]{64}$/);
        expect(PROGRESS_CERTIFIED_V5_REPAIR_RESULT_SHA256).toMatch(/^[0-9a-f]{64}$/);
        expect(PROGRESS_CERTIFIED_V5_DEPLOYABILITY_SUMMARY_SHA256).toMatch(/^[0-9a-f]{64}$/);
        expect(PROGRESS_CERTIFIED_V5_DEPLOYABILITY_ARRAY_JOB_ID).toBe("22340782");
        expect(PROGRESS_CERTIFIED_V5_DEPLOYABILITY_FINALIZER_JOB_ID).toBe("22341425");
    });
});
